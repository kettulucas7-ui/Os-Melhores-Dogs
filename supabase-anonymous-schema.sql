-- OSASCO HOT DOG — SUPABASE SEM CADASTRO
-- Os visitantes NÃO criam conta.
-- O frontend usa apenas a chave anon public.
--
-- IMPORTANTE:
-- Como não existe login, as políticas abaixo permitem que visitantes anônimos
-- insiram avaliações. Para produção, é recomendável adicionar rate limiting/
-- CAPTCHA e/ou uma Edge Function de moderação para reduzir spam.

create extension if not exists pgcrypto;

create table if not exists public.establishments (
  id bigint generated by default as identity primary key,
  name text not null,
  neighborhood text not null,
  price numeric(10,2) not null default 0,
  description text,
  hours text,
  image_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  establishment_id bigint not null references public.establishments(id) on delete cascade,
  author_name text not null check (char_length(author_name) between 2 and 40),
  rating integer not null check (rating between 1 and 5),
  comment text not null check (char_length(comment) between 2 and 300),
  photo_url text,
  photo_path text,
  created_at timestamptz not null default now()
);

create index if not exists reviews_establishment_id_idx
  on public.reviews(establishment_id);

create index if not exists reviews_created_at_idx
  on public.reviews(created_at desc);

alter table public.establishments enable row level security;
alter table public.reviews enable row level security;

drop policy if exists "establishments_public_read" on public.establishments;
create policy "establishments_public_read"
on public.establishments
for select
to anon, authenticated
using (true);

drop policy if exists "reviews_public_read" on public.reviews;
create policy "reviews_public_read"
on public.reviews
for select
to anon, authenticated
using (true);

drop policy if exists "reviews_public_insert" on public.reviews;
create policy "reviews_public_insert"
on public.reviews
for insert
to anon, authenticated
with check (
  rating between 1 and 5
  and char_length(author_name) between 2 and 40
  and char_length(comment) between 2 and 300
);

-- Storage público para as fotos.
insert into storage.buckets (id,name,public)
values ('review-photos','review-photos',true)
on conflict (id) do update set public=true;

drop policy if exists "review_photos_public_insert" on storage.objects;
create policy "review_photos_public_insert"
on storage.objects
for insert
to anon, authenticated
with check (
  bucket_id = 'review-photos'
  and lower(storage.extension(name)) in ('jpg','jpeg','png','webp')
);

drop policy if exists "review_photos_public_read" on storage.objects;
create policy "review_photos_public_read"
on storage.objects
for select
to anon, authenticated
using (bucket_id = 'review-photos');

